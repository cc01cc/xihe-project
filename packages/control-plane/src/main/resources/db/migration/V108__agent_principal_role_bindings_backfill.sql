-- PLAN-0629 (user ruling 2026-11-04): an agent principal's permission is a *role binding*.
--
-- The model: permissions live in the config surface (roles / role_permissions, V87),
-- and every subject — human account or agent principal — only gets "role bindings".
-- `agent_principals.scope` becomes a read-only compatibility field.
--
-- This migration converts the two implicit layers the workspace binding used to carry:
--
--   1. the binding row in `workspace_agents` (which froze a `permissions_snapshot`) becomes a
--      workspace-scoped `role_bindings` row with `subject_type = 'agent_principal'`;
--   2. that binding is materialized the same way `RoleGrantMaterializer` does it at runtime —
--      one `grants` row per role atom, `source = 'role'`, carrying the binding scope — so a database
--      that has not been touched by the application yet evaluates identically to a fresh bind.
--
-- Role choice (smallest role that still covers the frozen snapshot, compared on action class):
--   * snapshot ⊆ WS_VIEWER  -> WS_VIEWER
--   * snapshot ⊆ WS_EDITOR  -> WS_EDITOR
--   * snapshot ⊆ WS_OWNER   -> WS_OWNER
--   * anything else         -> the `agent-default` workspace role (created here from the union of
--                             the uncovered action classes), then bound.
--
-- Properties:
--   * idempotent  — `NOT EXISTS` guards the binding, `ON CONFLICT DO NOTHING` covers the unique keys
--                   (`uq_role_bindings`) and the materialized atom key (`uq_grants_role_atom`).
--   * additive    — no existing row is deleted or updated; the legacy ceiling rows
--                   (`source in ('agent_default','template')`) stay in place for rollback.
--   * no new mechanism — roles, role_permissions, role_bindings and `source='role'` grants are the
--                   V87 model, used exactly as `RoleGrantMaterializer` uses it.

-- ① The fallback role, only when some snapshot carries an atom no seeded workspace role covers.
INSERT INTO roles (id, name, display_name, description, is_system)
SELECT gen_random_uuid(), 'AGENT_DEFAULT', 'Agent default (legacy ceilings)',
       'PLAN-0629 backfill: action classes observed on existing agent workspace bindings that no '
       || 'seeded workspace role covers. Generated by V107, not user editable.',
       FALSE
WHERE EXISTS (
    SELECT 1
    FROM workspace_agents wa
    CROSS JOIN LATERAL jsonb_array_elements(wa.permissions_snapshot) AS atom
    WHERE NOT EXISTS (
        SELECT 1
        FROM roles r
        JOIN role_permissions rp ON rp.role_id = r.id
        WHERE r.name IN ('WS_VIEWER', 'WS_EDITOR', 'WS_OWNER')
          AND lower(rp.action_class) = lower(atom ->> 'actionClass')
    )
)
AND NOT EXISTS (SELECT 1 FROM roles existing WHERE existing.name = 'AGENT_DEFAULT');

-- Its atoms: every action class the seeded roles could not cover, at the wildcard resource (the
-- legacy snapshot was itself resource-agnostic).
INSERT INTO role_permissions (role_id, action_class, resource_pattern)
SELECT r.id, uncovered.action_class, '*'
FROM roles r
CROSS JOIN (
    SELECT DISTINCT lower(atom ->> 'actionClass') AS action_class
    FROM workspace_agents wa
    CROSS JOIN LATERAL jsonb_array_elements(wa.permissions_snapshot) AS atom
    WHERE NOT EXISTS (
        SELECT 1
        FROM roles seeded
        JOIN role_permissions rp ON rp.role_id = seeded.id
        WHERE seeded.name IN ('WS_VIEWER', 'WS_EDITOR', 'WS_OWNER')
          AND lower(rp.action_class) = lower(atom ->> 'actionClass')
    )
) AS uncovered
WHERE r.name = 'AGENT_DEFAULT'
ON CONFLICT DO NOTHING;

-- ② One workspace-scoped binding per existing (principal, workspace) pair, using the smallest
--    covering role. `ORDER BY rank` + `LIMIT 1` implements "WS_VIEWER before WS_EDITOR before
--    WS_OWNER"; a snapshot that no seeded role covers falls through to `agent-default`.
INSERT INTO role_bindings (id, role_id, subject_type, subject_id, scope_type, scope_id, granted_by)
SELECT gen_random_uuid(), chosen.role_id, 'agent_principal', wa.principal_id,
       'workspace', wa.workspace_id, p.created_by_user_id
FROM workspace_agents wa
JOIN agent_principals p ON p.id = wa.principal_id
CROSS JOIN LATERAL (
    SELECT candidate.role_id
    FROM (
        SELECT r.id AS role_id,
               CASE r.name WHEN 'WS_VIEWER' THEN 1 WHEN 'WS_EDITOR' THEN 2
                           WHEN 'WS_OWNER' THEN 3 ELSE 9 END AS rank,
               NOT EXISTS (
                   SELECT 1
                   FROM jsonb_array_elements(wa.permissions_snapshot) AS atom
                   WHERE NOT EXISTS (
                       SELECT 1
                       FROM role_permissions rp
                       WHERE rp.role_id = r.id
                         AND lower(rp.action_class) = lower(atom ->> 'actionClass')
                   )
               ) AS covers
        FROM roles r
        WHERE r.name IN ('WS_VIEWER', 'WS_EDITOR', 'WS_OWNER', 'AGENT_DEFAULT')
    ) AS candidate
    WHERE candidate.covers OR candidate.rank = 9
    ORDER BY candidate.covers DESC, candidate.rank
    LIMIT 1
) AS chosen
WHERE NOT EXISTS (
    SELECT 1
    FROM role_bindings existing
    WHERE existing.subject_type = 'agent_principal'
      AND existing.subject_id = wa.principal_id
      AND existing.scope_type = 'workspace'
      AND existing.scope_id = wa.workspace_id
)
ON CONFLICT DO NOTHING;

-- ③ Materialize exactly what `RoleGrantMaterializer` would write for those bindings: one grant row
--    per atom, `source='role'`, same scope as the binding. `uq_grants_role_atom` makes replays
--    no-ops, and only agent-principal bindings are touched, so user rows are never rewritten.
INSERT INTO grants (id, granter_type, granter_id, subject_type, subject_id, permissions, source,
                    scope_type, scope_id, read_state, created_at)
SELECT gen_random_uuid(), 'user', rb.granted_by, rb.subject_type, rb.subject_id,
       jsonb_build_array(jsonb_build_object('actionClass', rp.action_class,
                                            'resource', rp.resource_pattern)),
       'role', rb.scope_type, rb.scope_id, 'read', NOW()
FROM role_bindings rb
JOIN role_permissions rp ON rp.role_id = rb.role_id
WHERE rb.subject_type = 'agent_principal'
  AND rb.scope_type = 'workspace'
ON CONFLICT DO NOTHING;
