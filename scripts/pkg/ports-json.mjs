#!/usr/bin/env node
/**
 * PLAN-0632 D32-11: generate the packaged stack's `ports.json` from the single source of truth.
 *
 * The launcher that ships inside the installer runs on a clean Windows machine: it is a Java
 * program (no Node), so it cannot import `scripts/lib/stack-ports.mjs`. Rather than hand-copying
 * five numbers into a second file (which is exactly how port drift starts), the build renders
 * `ports.json` from the same module the dev stacks use, and `ports-json.test.mjs` asserts the
 * rendered document still matches `deriveStack()`.
 *
 * Contract for the packaged launcher: `ports` holds exactly the five keys below, each an integer
 * port on 127.0.0.1. `ui` is the Vite dev port; in packaged mode the SPA is served by the CP
 * (PLAN-0632 D32-06), so the launcher opens `http://127.0.0.1:<cp>/` and `ui` documents the
 * dev-lane value the stack reserves.
 *
 * Usage: `node scripts/pkg/ports-json.mjs [--stack stack-1] [--out <file>]`
 */
import { writeFileSync } from 'node:fs';
import { DEFAULT_STACK_ID, deriveStack, normalizeStackArg } from '../lib/stack-ports.mjs';

/** The five keys the packaged launcher reads. Order is the order written to the file. */
export const PORTS_JSON_KEYS = Object.freeze(['ui', 'cp', 'agent', 'runtime', 'postgres']);

/**
 * Render the document. No timestamp: the build must be byte-reproducible for the same stack, so
 * "when" is deliberately absent (the installer build records the build time in its own report).
 */
export function renderPortsJson(stackId = DEFAULT_STACK_ID) {
  const derived = deriveStack(stackId);
  const ports = {};
  for (const key of PORTS_JSON_KEYS) {
    ports[key] = derived.ports[key];
  }
  return (
    JSON.stringify(
      {
        $comment:
          'GENERATED by scripts/pkg/ports-json.mjs from scripts/lib/stack-ports.mjs (PLAN-0632 D32-11). Do not edit by hand.',
        stackId: derived.stackId,
        ports,
      },
      null,
      2,
    ) + '\n'
  );
}

/**
 * Parse a rendered document and fail loudly on drift instead of defaulting a missing port.
 * @returns {{stackId: string, ports: Record<string, number>}}
 */
export function parsePortsJson(text) {
  const document = JSON.parse(text);
  const ports = document?.ports;
  if (!ports || typeof ports !== 'object') {
    throw new Error('ports.json: missing "ports" object');
  }
  const parsed = {};
  for (const key of PORTS_JSON_KEYS) {
    const value = ports[key];
    if (!Number.isInteger(value) || value < 1 || value > 65535) {
      throw new Error(`ports.json: "${key}" must be an integer port in 1..65535, got ${JSON.stringify(value)}`);
    }
    parsed[key] = value;
  }
  const extra = Object.keys(ports).filter((key) => !PORTS_JSON_KEYS.includes(key));
  if (extra.length > 0) {
    throw new Error(`ports.json: unexpected port keys ${JSON.stringify(extra)}`);
  }
  return { stackId: document.stackId, ports: parsed };
}

function argValue(argv, flag, fallback) {
  const index = argv.indexOf(flag);
  return index >= 0 && argv[index + 1] ? argv[index + 1] : fallback;
}

const isMain = process.argv[1] && import.meta.url === new URL(`file:///${process.argv[1].replaceAll('\\', '/')}`).href;
if (isMain || process.argv[1]?.endsWith('ports-json.mjs')) {
  const argv = process.argv.slice(2);
  const stackId = normalizeStackArg(argValue(argv, '--stack', DEFAULT_STACK_ID));
  const out = argValue(argv, '--out', null);
  const text = renderPortsJson(stackId);
  if (out) {
    writeFileSync(out, text, 'utf8');
    console.log(`[ports-json] wrote ${out} (${stackId})`);
  } else {
    process.stdout.write(text);
  }
}
